    void PrimeIterator::init_range(size_t range_num)
    {
        int start = (int)(range_num << 16);
        if (start < (int)((1UL << 31) - (1 << 16)))
            _list.sieve_range(start, start + (1 << 16), _range);
        else
        {
            _list.sieve_range(start, (int)((1UL << 31) - 1), _range);
            _range.push_back((int)((1UL << 31) - 1));
        }
        _range_pos = _31bit_prime_pos[range_num];
    }

    PrimeIterator& PrimeIterator::operator+=(ptrdiff_t offset)
    {
        if (offset < 0 && _cur < (size_t)-offset)
            _cur = 0;
        else
            _cur += offset;
        if (_cur > 105097564)
            _cur = 105097564;
        if (_cur < _list.size())
            return *this;
        if (_cur >= _range_pos && _cur - _range_pos < _range.size())
            return *this;

        init_31bit_prime_pos();
        size_t range_num = 0;
        if (_cur >= _range_pos && ((_cur - _range_pos) >> 16) < 10)
            for (range_num = _range.empty() ? 0 : _range[0] >> 16; _31bit_prime_pos[range_num + 1] <= _cur; range_num++);
        else if (_cur < _range_pos && ((_range_pos - _cur) >> 16) < 10)
            for (range_num = _range[0] >> 16; _31bit_prime_pos[range_num] > _cur; range_num--);
        else
            range_num = (size_t)(upper_bound(_31bit_prime_pos.begin(), _31bit_prime_pos.end(), _cur) - _31bit_prime_pos.begin()) - 1;
        init_range(range_num);
        return *this;
    }

    PrimeIterator PrimeIterator::find(int prime)
    {
        PrimeIterator it = get();
        if (prime <= it._list.primes.back())
        {
            it._cur = (size_t)(upper_bound(it._list.primes.begin(), it._list.primes.end(), prime) - it._list.primes.begin());
            if (it._cur > 0)
                it._cur--;
        }
        else
        {
            init_31bit_prime_pos();
            it.init_range(prime >> 16);
            it._cur = it._range_pos + (size_t)(upper_bound(it._range.begin(), it._range.end(), prime) - it._range.begin());
            if (it._cur > it._range_pos)
                it._cur--;
            else
                it--;
        }
        return it;
    }

